/**
 * Regenerates `src/frozen.ts` from the hand-written vectors in `src/vectors.ts`.
 *
 * Run this only when a hash-construction change is intended. Doing so means a
 * NORM_VERSION bump and a full shard regen, because every published
 * hash becomes invalid.
 *
 *   bun run packages/shared/scripts/freeze-vectors.ts
 */

import { hashNormalized } from '../src/hash.ts';
import { NORM_VERSION } from '../src/normalize.ts';
import { GOLDEN_VECTORS } from '../src/vectors.ts';

const normalizedForms = [
  ...new Set(
    GOLDEN_VECTORS.map((vector) => vector.normalized).filter((form): form is string => form !== null),
  ),
].sort();

const entries: string[] = [];
for (const normalized of normalizedForms) {
  const { full, h, shard } = await hashNormalized(normalized);
  entries.push(
    `  ${JSON.stringify(normalized)}: { full: '${full}', h: '${h}', shard: '${shard}' },`,
  );
}

const file = `/**
 * GENERATED by scripts/freeze-vectors.ts — do not edit by hand.
 *
 * Frozen digests for every normalized form in \`vectors.ts\`, at NORM_VERSION ${NORM_VERSION}.
 * A diff here means every published hash changed.
 */

export interface FrozenHash {
  readonly full: string;
  readonly h: string;
  readonly shard: string;
}

export const FROZEN_HASHES: Readonly<Record<string, FrozenHash>> = {
${entries.join('\n')}
};
`;

await Bun.write(new URL('../src/frozen.ts', import.meta.url), file);
console.info(`froze ${normalizedForms.length} normalized forms at NORM_VERSION ${NORM_VERSION}`);
